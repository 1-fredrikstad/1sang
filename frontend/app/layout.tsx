import type { Metadata } from 'next';
import { Geist, Geist_Mono } from 'next/font/google';
import './globals.css';
import ConditionalHeader from '@/src/components/global/ConditionalHeader';
import ConditionalNavbar from '@/src/components/global/ConditionalNavbar';
import { AuthProvider } from '@/src/context/AuthContext';
import { ThemeProvider } from '@/src/context/ThemeProvider';
import { cookies } from 'next/headers';
import type { ColorHeader } from '@/src/types/theme';

const geistSans = Geist({
  variable: '--font-geist-sans',
  subsets: ['latin'],
});

const geistMono = Geist_Mono({
  variable: '--font-geist-mono',
  subsets: ['latin'],
});

export const metadata: Metadata = {
  title: 'Sanger under liljen',
  description: 'Generated by G01',
};

export default async function RootLayout({ children }: { children: React.ReactNode }) {
  const cookieStore = await cookies();
  const themeCookie = cookieStore.get('theme')?.value as 'light_mode' | 'dark_mode' | undefined;
  const initialMode = themeCookie ?? 'light_mode';
  const headerThemeCookie = cookieStore.get('headerTheme')?.value as ColorHeader | undefined;
  const defaultHeaderTheme =
    headerThemeCookie ?? (initialMode === 'dark_mode' ? 'dark_gray' : 'light_yellow');

  return (
    <AuthProvider>
      <html lang="en" data-mode={initialMode} data-theme={defaultHeaderTheme}>
        <head>
          <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />
          <link rel="manifest" href="/manifest.webmanifest" />
          <link rel="icon" href="/favicon.ico" sizes="32x32" />
          <link rel="apple-touch-icon" href="/apple-touch-icon.png" sizes="180x180" />
        </head>
        <body
          className={`${geistSans.variable} ${geistMono.variable} antialiased overflow-x-hidden`}
        >
          <ThemeProvider initialMode={initialMode}>
            <ConditionalHeader />

            <main className="pb-[calc(80px+env(safe-area-inset-bottom))] md:pb-20">{children}</main>

            <ConditionalNavbar />
          </ThemeProvider>
        </body>
      </html>
    </AuthProvider>
  );
}
